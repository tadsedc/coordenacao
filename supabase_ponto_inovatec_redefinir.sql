-- Administração das declarações. Preserva auditoria, presenças e suspensões.
begin;
create table if not exists public.inovatec_pontos_redefinicoes(
 id bigint generated by default as identity primary key,
 estudante_id bigint not null references public.inovatec_estudantes(id),
 codigo_anterior uuid not null,
 declaracao_anterior jsonb not null,
 motivo text not null check(length(trim(motivo)) between 5 and 1000),
 responsavel uuid not null references auth.users(id),
 redefinido_em timestamptz not null default now()
);
alter table public.inovatec_pontos_redefinicoes enable row level security;
revoke all on public.inovatec_pontos_redefinicoes from anon,authenticated;
grant select on public.inovatec_pontos_redefinicoes to authenticated;
drop policy if exists coord_historico_redefinicao on public.inovatec_pontos_redefinicoes;
create policy coord_historico_redefinicao on public.inovatec_pontos_redefinicoes for select to authenticated using(public.usuario_e_coordenador());
create or replace function public.redefinir_ponto_inovatec(p_codigo uuid,p_motivo text)
returns void language plpgsql security definer set search_path=public as $$
declare ponto public.inovatec_pontos%rowtype;estudante bigint;
begin
 if not coalesce(public.usuario_e_coordenador(),false) then raise exception 'Acesso exclusivo da coordenação.';end if;
 if length(trim(coalesce(p_motivo,''))) not between 5 and 1000 then raise exception 'Informe um motivo entre 5 e 1000 caracteres.';end if;
 select estudante_id into estudante from public.inovatec_pontos where id=p_codigo;
 if not found then raise exception 'A declaração não existe ou já foi redefinida. Atualize a lista.';end if;
 -- Mesma ordem de bloqueio da emissão e da suspensão.
 perform 1 from public.inovatec_estudantes where id=estudante for update;
 select * into ponto from public.inovatec_pontos where id=p_codigo for update;
 if not found then raise exception 'A declaração já foi redefinida. Atualize a lista.';end if;
 insert into public.inovatec_pontos_redefinicoes(estudante_id,codigo_anterior,declaracao_anterior,motivo,responsavel)
 values(ponto.estudante_id,ponto.id,to_jsonb(ponto),trim(p_motivo),auth.uid());
 delete from public.inovatec_pontos where id=ponto.id;
end $$;
revoke all on function public.redefinir_ponto_inovatec(uuid,text) from public,anon;
grant execute on function public.redefinir_ponto_inovatec(uuid,text) to authenticated;
notify pgrst,'reload schema';
commit;
