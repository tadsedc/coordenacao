begin;
create table if not exists public.inovatec_ponto_suspensoes(
 estudante_id bigint primary key references public.inovatec_estudantes(id),
 suspenso boolean not null, motivo_interno text,
 atualizado_por uuid not null references auth.users(id),
 atualizado_em timestamptz not null default now()
);
create table if not exists public.inovatec_ponto_suspensoes_log(
 id bigint generated by default as identity primary key,
 estudante_id bigint not null references public.inovatec_estudantes(id),
 suspenso boolean not null,motivo_interno text,
 responsavel uuid not null references auth.users(id),criado_em timestamptz not null default now()
);
alter table public.inovatec_ponto_suspensoes enable row level security;
alter table public.inovatec_ponto_suspensoes_log enable row level security;
revoke all on public.inovatec_ponto_suspensoes,public.inovatec_ponto_suspensoes_log from anon,authenticated;
grant select on public.inovatec_ponto_suspensoes,public.inovatec_ponto_suspensoes_log to authenticated;
drop policy if exists coord_suspensoes on public.inovatec_ponto_suspensoes;
create policy coord_suspensoes on public.inovatec_ponto_suspensoes for select to authenticated using(public.usuario_e_coordenador());
drop policy if exists coord_suspensoes_log on public.inovatec_ponto_suspensoes_log;
create policy coord_suspensoes_log on public.inovatec_ponto_suspensoes_log for select to authenticated using(public.usuario_e_coordenador());
create or replace function public.definir_suspensao_ponto_inovatec(p_estudante bigint,p_suspenso boolean,p_motivo text)
returns void language plpgsql security definer set search_path=public as $$
begin
 if not coalesce(public.usuario_e_coordenador(),false) then raise exception 'Acesso exclusivo da coordenação.';end if;
 if p_suspenso is null or length(coalesce(p_motivo,''))>1000 then raise exception 'Parâmetros inválidos.';end if;
 -- Mesmo bloqueio da emissão: uma suspensão confirmada impede a emissão seguinte.
 perform 1 from public.inovatec_estudantes where id=p_estudante for update;
 if not found then raise exception 'Estudante não encontrado.';end if;
 insert into public.inovatec_ponto_suspensoes values(p_estudante,p_suspenso,nullif(trim(p_motivo),''),auth.uid(),now())
 on conflict(estudante_id) do update set suspenso=excluded.suspenso,motivo_interno=excluded.motivo_interno,atualizado_por=excluded.atualizado_por,atualizado_em=excluded.atualizado_em;
 insert into public.inovatec_ponto_suspensoes_log(estudante_id,suspenso,motivo_interno,responsavel) values(p_estudante,p_suspenso,nullif(trim(p_motivo),''),auth.uid());
end $$;
revoke all on function public.definir_suspensao_ponto_inovatec(bigint,boolean,text) from public;
grant execute on function public.definir_suspensao_ponto_inovatec(bigint,boolean,text) to authenticated;
create or replace function public.acessar_ponto_inovatec(p_nome text,p_email text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare e public.inovatec_estudantes%rowtype;c public.inovatec_pontos%rowtype;s jsonb;opcoes jsonb;
begin
 select * into e from public.inovatec_estudantes where nome_normalizado=public.normalizar_nome_inovatec(p_nome) and lower(email)=lower(trim(p_email)) limit 1;
 if not found then raise exception 'Nome completo e e-mail não encontrados na inscrição do evento.';end if;
 select * into c from public.inovatec_pontos where estudante_id=e.id;
 if found then return jsonb_build_object('declaracao',jsonb_build_object('codigo',c.id,'nome',c.nome_estudante,'curso',c.curso,'disciplina',c.disciplina,'pontos',c.pontos,'emitido_em',c.emitido_em));end if;
 if exists(select 1 from public.inovatec_ponto_suspensoes where estudante_id=e.id and suspenso) then return jsonb_build_object('suspenso',true,'nome',e.nome_completo);end if;
 if not e.ativo then raise exception 'Seu cadastro não está habilitado. Consulte a coordenação.';end if;
 s:=public.situacao_ponto_inovatec(e.id);
 if not (s->>'concluido')::boolean then return jsonb_build_object('nome',e.nome_completo,'situacao',s);end if;
 select coalesce(jsonb_agg(jsonb_build_object('id',d.id,'curso',d.curso,'disciplina',d.disciplina,'semestre',d.semestre) order by d.curso,d.disciplina),'[]'::jsonb)
 into opcoes from public.matriz_disciplinas d where d.ativa and d.curso in('ADS','EDC');
 return jsonb_build_object('nome',e.nome_completo,'situacao',s,'disciplinas',opcoes);
end $$;

create or replace function public.emitir_ponto_inovatec(p_nome text,p_email text,p_disciplina bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare e public.inovatec_estudantes%rowtype;d public.matriz_disciplinas%rowtype;
begin
 -- O bloqueio impede duas escolhas concorrentes por um mesmo estudante.
 select * into e from public.inovatec_estudantes where nome_normalizado=public.normalizar_nome_inovatec(p_nome) and lower(email)=lower(trim(p_email)) limit 1 for update;
 if not found then raise exception 'Dados de inscrição não encontrados.';end if;
 if exists(select 1 from public.inovatec_pontos where estudante_id=e.id) then return public.acessar_ponto_inovatec(p_nome,p_email);end if;
 if exists(select 1 from public.inovatec_ponto_suspensoes where estudante_id=e.id and suspenso) then raise exception 'Sua solicitação está temporariamente indisponível. Preencha o questionário enviado pela Coordenação no grupo de WhatsApp e entre em contato solicitando a liberação. ADS: tads@aems.edu.br. EDC: eng_computacao@aems.edu.br.';end if;
 if not e.ativo or not (public.situacao_ponto_inovatec(e.id)->>'concluido')::boolean then raise exception 'É necessário concluir as duas palestras e todos os encontros de ao menos uma oficina válida. E-Games não conta.';end if;
 select * into d from public.matriz_disciplinas where id=p_disciplina and ativa and curso in('ADS','EDC');
 if not found then raise exception 'Selecione uma disciplina válida da matriz.';end if;
 insert into public.inovatec_pontos(estudante_id,disciplina_id,nome_estudante,curso,disciplina) values(e.id,d.id,e.nome_completo,d.curso,d.disciplina);
 return public.acessar_ponto_inovatec(p_nome,p_email);
end $$;

revoke all on function public.acessar_ponto_inovatec(text,text),public.emitir_ponto_inovatec(text,text,bigint) from public;
grant execute on function public.acessar_ponto_inovatec(text,text),public.emitir_ponto_inovatec(text,text,bigint) to anon,authenticated;
notify pgrst,'reload schema';
commit;

